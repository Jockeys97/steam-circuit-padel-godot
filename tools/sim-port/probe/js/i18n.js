export function t(key, params = {}) {
  const table = DICT[currentLang] ?? DICT.it;
  let text = table[key] ?? DICT.it[key] ?? key;
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}
