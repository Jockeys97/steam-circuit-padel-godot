#!/usr/bin/env python3
"""Arena kit image batch — resumable generator (arena-kit-v1).

Reads a prompt pack from ``tools/arena-kit/prompts/<arena>.json`` and produces
``art/arena-kits/<arena>/<slot>.png`` images that satisfy the Meshy-readiness
checklist (KIT-STANDARD §4), appending every attempt to the spend ledger
``art/arena-kits/image-spend.json`` and journaling progress to
``run/tmp/arena-kit/image-batch-journal.txt``.

Backend ladder (meshy recipe: image-prototyping.md §6, S25):
  1. ``hermes-tool``  — the Hermes image tool implementation. Imports the same
     provider module the in-session ``image_generate`` tool routes to
     (``plugins.image_gen.openai``: OpenAIImageGenProvider) inside the Hermes
     source tree, resolving the key through Hermes's own secret scope
     (``agent.secret_scope.get_secret``). No key is ever printed or handled here.
  2. ``jobs``         — when the provider is unavailable, emit the exact job
     payloads to ``run/tmp/arena-kit/jobs-pending.json`` so an in-session agent
     can run them with the native image tool and then ``--install`` each result.

Resumability: a slot whose delivered file already exists and passes the
programmatic check is skipped. ``--regen`` archives the rejected attempt under
``_rejected/`` and re-runs that one slot (policy: at most one regen per slot).

Commands:
  gen_assets.py --status                     ledger cap/remaining + worklist counts
  gen_assets.py --list                       pending slots per arena
  gen_assets.py --set-cap N --cap-reason R   raise/record the ledger cap
  gen_assets.py --run [--arena X] [--slots a,b] [--limit N]
  gen_assets.py --regen --arena X --slot S
  gen_assets.py --install CACHE --arena X --slot S   install an externally produced image
  gen_assets.py --verify [--arena X]         programmatic checklist over delivered files
  gen_assets.py --sheet --arena X            contact sheet for visual review
  gen_assets.py --manifest --arena X         write art/arena-kits/<arena>/MANIFEST.md
"""

