PROMPTS = os.path.join(REPO, "tools", "arena-kit", "prompts")
KITS = os.path.join(REPO, "art", "arena-kits")
LEDGER = os.path.join(KITS, "image-spend.json")
JOURNAL = os.path.join(REPO, "run", "tmp", "arena-kit", "image-batch-journal.txt")
TMP = os.path.join(REPO, "run", "tmp", "arena-kit")
HERMES_SRC = os.path.expanduser("~/.hermes/hermes-agent")
HERMES_PROFILE_HOME = os.path.expanduser("~/.hermes/profiles/dev-work")

